class AssetError(RuntimeError):
    """资产派生失败（manifest 缺失 / 结构非法 / 生成物缺失）——调用方按失败处理"""


# ── manifest 读取与校验 ──────────────────────────────────────────────

def load_manifest(path: Path) -> list[dict]:
    """
    读并校验 manifest，返回 `types` 列表（顺序即注册顺序，保持 manifest 原序）。

    :param path: manifest 文件路径
    :raises AssetError: 文件缺失 / 非法 JSON / 结构不符合 §5.1
    """
    if not path.is_file():
        raise AssetError(
            f"找不到 manifest：{path}\n"
            "  请先运行：node scripts/gen_file_assoc_manifest.mjs"
        )
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError, UnicodeDecodeError) as exc:
        raise AssetError(f"manifest 读取/解析失败（{path}）：{exc}") from exc

    if not isinstance(raw, dict):
        raise AssetError(f"manifest 顶层必须是对象（{path}）")
    if raw.get("version") != MANIFEST_VERSION:
        raise AssetError(
            f"manifest version={raw.get('version')!r}，本脚本只认 {MANIFEST_VERSION}"
            "（§5.1 的 version 字段）"
        )
    types = raw.get("types")
    if not isinstance(types, list) or not types:
        raise AssetError("manifest.types 必须是非空数组（§5.1）")

    seen: dict[str, int] = {}
    result: list[dict] = []
    for index, entry in enumerate(types):
        if not isinstance(entry, dict):
            raise AssetError(f"manifest.types[{index}] 不是对象")
        ext = entry.get("ext")
        if not isinstance(ext, str) or not _EXT_RE.match(ext):
            raise AssetError(
                f"manifest.types[{index}].ext={ext!r} 非法（要求小写、不含点与通配符）"
            )
        if ext in seen:
            raise AssetError(f"manifest 扩展名重复：{ext}（types[{index}] 与 types[{seen[ext]}]）")
        seen[ext] = index
        mime = entry.get("mime")
        if not isinstance(mime, list) or not mime or not all(
            isinstance(m, str) and m for m in mime
        ):
            raise AssetError(f"manifest.types[{index}].mime 必须是非空字符串数组")
        result.append({"ext": ext, "label": entry.get("label", ext), "mime": list(mime)})
    return result


def collect_mime_types(types: list[dict]) -> list[str]:
    """
    汇总 MIME 清单：manifest 各条目的 `mime` 按**首次出现顺序**去重，末尾追加 JFLove 自有类型。

    :param types: `load_manifest()` 的返回值
    :returns: 去重后的 MIME 列表（顺序稳定 ⇒ 生成物可复现）
    """
    mimes: dict[str, None] = {}
    for entry in types:
        for mime in entry["mime"]:
            mimes.setdefault(mime, None)
    mimes.setdefault(SELF_MIME_TYPE, None)
    return list(mimes)


# ── ① Linux 共享 MIME 包 ─────────────────────────────────────────────

def render_mime_xml(types: list[dict]) -> str:
    """
    渲染 `packaging/linux/jflove.xml`（`shared-mime-info` 格式，§6.7.3）。

    只新增 `application/x-jflove-text` 一个类型，把 manifest 的全部扩展名作为
    `<glob pattern="*.ext"/>` 挂在它下面；**不重定义**任何系统既有 MIME 类型。

    :param types: `load_manifest()` 的返回值
    :returns: XML 文本（UTF-8 无 BOM，以换行结尾）
    """
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<!--",
        "  JFLove 文件关联 MIME 包（生成物，请勿手改）。",
        "  生成：python scripts/gen_file_assoc_assets.py",
        "  一致性判据：再跑一次生成脚本的 check 模式（退出码 0 = 与 manifest 一致；详见脚本用法）",
        f"  唯一真相：ui/src/config/scratch-types.ts 的 TYPES → ui/public/{MANIFEST_NAME}",
        "  设计依据：v1.6.0 第 6.7.3 节（Linux RPM：MIME 包 + .desktop MimeType + update-mime-database）。",
        "  落地方式：安装到 share/mime/packages/jflove.xml，由 RPM 的 post/postun 跑 update-mime-database。",
        "  注意：本包不用 xdg-mime default、不写 ~/.config/mimeapps.list（不改默认程序，D18）。",
        "-->",
        '<mime-info xmlns="http://www.freedesktop.org/standards/shared-mime-info">',
        f'  <mime-type type="{SELF_MIME_TYPE}">',
        "      <comment>JFLove text file</comment>",
        '      <comment xml:lang="zh_CN">JFLove 文本文件</comment>',
        '      <icon name="jflove"/>',
    ]
    lines.extend(f'      <glob pattern="*.{entry["ext"]}"/>' for entry in types)
    lines.extend(["  </mime-type>", "</mime-info>", ""])
    return "\n".join(lines)


# ── ② Linux .desktop 的 MimeType 行 ──────────────────────────────────

def render_mime_line(mimes: list[str]) -> str:
    """
    渲染 `.desktop` 的 `MimeType=` 行（`;` 分隔、以 `;` 结尾，§6.7.3）。

    :param mimes: `collect_mime_types()` 的返回值
    :returns: 一行文本（不含换行）
    """
    return "MimeType=" + "".join(f"{mime};" for mime in mimes)


def _anchor_index(lines: list[str]) -> int:
    """按 `Icon=` → `Exec=` → `Categories=` 的优先级找插入锚点（都没有则 -1）。"""
    for prefix in ("Icon=", "Exec=", "Categories="):
        found = next((i for i, line in enumerate(lines) if line.startswith(prefix)), -1)
        if found >= 0:
            return found
    return -1


def render_desktop(text: str, mimes: list[str]) -> str:
    """
    幂等重写 `.desktop` 的 `MimeType=` 块（其余人工维护的行**逐行保留**）。

    重写规则：
      ① 已有**有序成对**的标记注释 ⇒ 原位置替换（第二次运行起完全幂等）；
      ② 标记缺失 / 残缺 / 重复 ⇒ 清掉所有标记行，再插到 `Icon=` 之后
         （无 `Icon=` 时退 `Exec=`、`Categories=`，都无则追加到末尾）。

    两种路径都会顺手清掉标记块之外的 `MimeType=` 行：**这个键归生成器所有**，
    重复的 `MimeType` 键在不同实现下"谁生效"并不确定，留着就是个隐患。

    :param text: 磁盘上的 `.desktop` 文本
    :param mimes: `collect_mime_types()` 的返回值
    :returns: 重写后的文本（以单个换行结尾）
    """
    block = [DESKTOP_MARK_BEGIN, render_mime_line(mimes), DESKTOP_MARK_END]
    lines = text.splitlines()

    def owned_free(segment: list[str]) -> list[str]:
        """去掉生成器拥有的行：标记注释 + 任何 `MimeType=` 行。"""
        return [line for line in segment
                if line.strip() not in (DESKTOP_MARK_BEGIN, DESKTOP_MARK_END)
                and not line.startswith("MimeType=")]

    begin = next((i for i, line in enumerate(lines)
                  if line.strip() == DESKTOP_MARK_BEGIN), -1)
    end = next((i for i, line in enumerate(lines[begin + 1:], start=begin + 1)
                if line.strip() == DESKTOP_MARK_END), -1) if begin >= 0 else -1

    if begin >= 0 and end > begin:
        result = owned_free(lines[:begin]) + block + owned_free(lines[end + 1:])
    else:
        cleaned = owned_free(lines)
        anchor = _anchor_index(cleaned)
        if anchor < 0:
            result = cleaned + block
        else:
            result = cleaned[:anchor + 1] + block + cleaned[anchor + 1:]
    return "\n".join(result) + "\n"


# ── ③ Windows Inno Setup 注册片段 ────────────────────────────────────

def render_iss(types: list[dict]) -> str:
    """
    渲染 `packaging/windows/file-assoc.iss`（`jflove.iss` 的 `[Registry]` 段内片段，§6.7.2）。

    片段形态（**不含 `[Registry]` 段头**，由 `jflove.iss` 在段内 `#include`）：
      - 开头的 `#define` 供 `[Code]` 卸载清理使用（ISPP 会把它们预处理掉，不进入解析后的脚本）；
      - 其后是逐条的 `Root: HKCU; Subkey: ...` 注册行。

    注册内容严格照 §6.7.2：应用默认值 / `DefaultIcon` / `shell\\open\\command` /
    `SupportedTypes` 逐扩展名**空值**（`ValueType: string; ValueData: ""` —— Inno 的
    `ValueType: none` 只建键不建值，本机 ISCC 6 实测确认，故不能用它）。

    :param types: `load_manifest()` 的返回值
    :returns: ISPP 片段文本（UTF-8 无 BOM，以换行结尾）
    """
    exts = [entry["ext"] for entry in types]
    exts_csv = ",".join(exts)
    lines = [
        "; ---------------------------------------------------------------------------",
        "; JFLove 文件关联注册片段（生成物，请勿手改）",
        ";",
        f"; 生成命令：{_GEN_CMD}",
        f"; 一致性判据：{_CHECK_CMD}",
        "; 唯一真相：ui/src/config/scratch-types.ts 的 TYPES",
        f";           → ui/public/{MANIFEST_NAME}（随 dist/ 一起进包，见设计 §6.7.1）",
        ";",
        "; 本文件是【段内片段】：由 packaging/windows/jflove.iss 在 [Registry] 段里 #include。",
        "; 开头的 #define 会被 ISPP 预处理掉，供 [Code] 的卸载清理使用（§6.7.2）。",
        ";",
        "; 注册位置（HKCU；管理员安装也写 HKCU，理由见设计 §6.7.2 的裁决表）：",
        ";   <应用键>                          默认值 = 应用可读名称",
        ";   <应用键>\\DefaultIcon              默认值 = \"{app}\\JFLove.exe\",0",
        ";   <应用键>\\shell\\open\\command     默认值 = \"{app}\\JFLove.exe\" \"%1\"",
        ";   <应用键>\\SupportedTypes           每个扩展名一个空值",
        "; 其中 <应用键> = HKCU\\Software\\Classes\\Applications\\JFLove.exe",
        ";",
        "; ⚠ 严格不写（D18 / AC-43 ②）：",
        ";   ❌ HKCU\\Software\\Classes\\.<ext>            （会抢占默认程序）",
        ";   ❌ ...\\FileExts\\.<ext>\\UserChoice           （同样会抢占默认程序）",
        ";   ❌ ChangesAssociations=yes / 任何「设为默认」的 API",
        ";   SupportedTypes 的【值名】带前导点（\".json\"）是 Windows 的规定（值名 = 文件扩展名），",
        ";   与上面禁止的 Software\\Classes\\.<ext>【键】不是一回事。",
        "; ---------------------------------------------------------------------------",
        "",
        "; [Code] 卸载清理用的清单（逗号分隔，顺序 = manifest 顺序）",
        f'#define FILE_ASSOC_EXTS "{exts_csv}"',
        "; 扩展名条数（装配期自检用；与 ui/public 里的清单必然相等）",
        f"#define FILE_ASSOC_COUNT {len(exts)}",
        "; 注册表里的应用可执行文件名 + 应用键全路径（[Code] 删整键时用）",
        f'#define FILE_ASSOC_EXE "{APP_EXE_NAME}"',
        f'#define FILE_ASSOC_APP_KEY "{APP_REG_PATH}"',
        "",
        "; 构建期护栏：Applications 子键名必须与真实可执行文件名一致，否则「打开方式」列不出本应用",
        "#if AppExeName != FILE_ASSOC_EXE",
        "  #error jflove.iss 的 AppExeName 与文件关联注册片段不一致（重跑 gen_file_assoc_assets.py）",
        "#endif",
        "",
        "; ① 应用标识 / 图标 / 打开命令（AC-43 ① 的判据就是该键存在）",
        f'Root: HKCU; Subkey: "{APP_REG_PATH}"; ValueType: string; ValueName: ""; '
        f'ValueData: "{APP_DISPLAY_NAME}"',
        f'Root: HKCU; Subkey: "{APP_REG_PATH}\\DefaultIcon"; ValueType: string; ValueName: ""; '
        f'ValueData: "{{app}}\\{APP_EXE_NAME},0"',
        f'Root: HKCU; Subkey: "{APP_REG_PATH}\\shell\\open\\command"; ValueType: string; '
        f'ValueName: ""; ValueData: """{{app}}\\{APP_EXE_NAME}"" ""%1"""',
        "",
        "; ② SupportedTypes：每个扩展名一个空值（空 REG_SZ；值名带前导点，见文件头说明）",
    ]
    lines.extend(
        f'Root: HKCU; Subkey: "{APP_REG_PATH}\\SupportedTypes"; ValueType: string; '
        f'ValueName: ".{ext}"; ValueData: ""'
        for ext in exts
    )
    lines.append("")
    return "\n".join(lines)


# ── 目标清单与写盘 ───────────────────────────────────────────────────

def target_paths(root: Path, manifest: Path) -> dict[str, Path]:
    """解析三处生成物 + manifest 的路径（`--root` 可整体搬走，便于夹具验证）。"""
    return {
        "manifest": manifest,
        "xml": root / "packaging" / "linux" / "jflove.xml",
        "desktop": root / "packaging" / "linux" / "jflove.desktop",
        "iss": root / "packaging" / "windows" / "file-assoc.iss",
    }


def render_all(types: list[dict], desktop_text: str) -> dict[str, str]:
    """按 manifest 渲染三处生成物的**期望内容**。"""
    return {
        "xml": render_mime_xml(types),
        "desktop": render_desktop(desktop_text, collect_mime_types(types)),
        "iss": render_iss(types),
    }


def _print_diff(name: str, disk: str, expected: str) -> None:
    """打印"磁盘 vs 派生"的逐行 diff（生成物缺失时由调用方另给提示）。"""
    diff = difflib.unified_diff(
        disk.splitlines(keepends=True), expected.splitlines(keepends=True),
        fromfile=f"{name}（磁盘）", tofile=f"{name}（派生）", n=1,
    )
    sys.stderr.writelines(diff)


# ── CLI ──────────────────────────────────────────────────────────────

def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="gen_file_assoc_assets.py",
        description="从 ui/public/file-assoc.manifest.json 派生 jflove.xml / .desktop MimeType / "
                    "file-assoc.iss（设计 v1.6.0 §5.1 §6.7）",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "示例：\n"
            f"  {_GEN_CMD}                    生成三处资产（默认模式）\n"
            f"  {_CHECK_CMD}                      只比对：一致 exit 0 / 不一致 exit 1\n"
            f"  {_CHECK_CMD} --manifest x.json    用夹具 manifest 反向验证（加一项 .zzz ⇒ exit 1）\n"
        ),
    )
    parser.add_argument("--root", type=Path, default=DESKTOP_ROOT,
                        help=f"jflove-desktop 根目录（默认 {DESKTOP_ROOT}）")
    parser.add_argument("--manifest", type=Path, default=None,
                        help=f"manifest 路径（默认 <root>/ui/public/{MANIFEST_NAME}）")
    parser.add_argument("--src", type=Path, default=None,
                        help="TS 真相文件路径（默认 <root>/ui/src/config/scratch-types.ts，仅 --check 用）")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="生成/覆盖三处资产（默认）")
    mode.add_argument("--check", action="store_true",
                      help="只比对不写盘：一致 exit 0，不一致 exit 1 并打印 diff")
    parser.add_argument("--no-derive-check", action="store_true",
                        help="--check 时跳过「manifest ↔ scratch-types.ts」核对（离线夹具用；"
                             "生产构建不要用）")
    return parser


def main(argv: list[str] | None = None) -> int:
    """入口：返回进程退出码（0 成功 / 1 失败）。"""
    args = _build_parser().parse_args(argv)
    root: Path = args.root.resolve()
    manifest = (args.manifest or (root / "ui" / "public" / MANIFEST_NAME)).resolve()
    src = (args.src or (root / "ui" / "src" / "config" / "scratch-types.ts")).resolve()
    paths = target_paths(root, manifest)

    try:
        types = load_manifest(manifest)
    except AssetError as exc:
        print(f"[gen-file-assoc-assets] 失败：{exc}", file=sys.stderr)
        return 1

    failures: list[str] = []

    # ① manifest ↔ 唯一手写真相（重跑 Node 派生链，不在 Python 里复刻格式）
    if args.check and not args.no_derive_check:
        failures.extend(_check_manifest_derivation(src, manifest))

    desktop_path = paths["desktop"]
    if not desktop_path.is_file():
        print(f"[gen-file-assoc-assets] 失败：找不到 {desktop_path}", file=sys.stderr)
        return 1
    expected = render_all(types, desktop_path.read_text(encoding="utf-8"))

    if not args.check:
        for key in ("xml", "desktop", "iss"):
            target = paths[key]
            body = expected[key]
            if target.is_file() and target.read_text(encoding="utf-8") == body:
                print(f"[gen-file-assoc-assets] 已是最新：{_rel(target)}")
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(body, encoding="utf-8")
            print(f"[gen-file-assoc-assets] 已生成：{_rel(target)}")
        print(f"[gen-file-assoc-assets] 完成：{len(types)} 个扩展名，"
              f"{len(collect_mime_types(types))} 个 MIME 类型（含 {SELF_MIME_TYPE}）")
        return 0

    # ② 资产 ↔ manifest
    for key in ("xml", "desktop", "iss"):
        target = paths[key]
        if not target.is_file():
            failures.append(f"缺少生成物：{_rel(target)}（请运行 {_GEN_CMD}）")
            continue
        disk = target.read_text(encoding="utf-8")
        if disk != expected[key]:
            failures.append(f"与 manifest 派生结果不一致：{_rel(target)}")
            _print_diff(_rel(target), disk, expected[key])

    if failures:
        print("\n[gen-file-assoc-assets] 失败：一致性核对未通过", file=sys.stderr)
        for item in failures:
            print(f"  - {item}", file=sys.stderr)
        print(f"\n  修法：{_GEN_CMD}（重新生成；不要手改生成物）", file=sys.stderr)
        return 1

    print(f"[gen-file-assoc-assets] 一致：manifest（{len(types)} 条）+ 三处生成物 "
          f"（jflove.xml / jflove.desktop / file-assoc.iss）")
    return 0


def _check_manifest_derivation(src: Path, manifest: Path) -> list[str]:
    """
    重跑 `gen_file_assoc_manifest.mjs` 并与磁盘 manifest 逐字节比对。

    Node 是派生链的唯一实现（Python 侧**不**复刻 JSON 渲染格式，避免双实现漂移）；
    构建机无 Node 时**响亮告警但不冒充通过**（该环境的资产核对仍然照做）。

    :param src: `scratch-types.ts` 路径
    :param manifest: 磁盘 manifest 路径
    :returns: 失败原因列表（空列表 = 通过或已告警跳过）
    """
    if not src.is_file():
        return [f"找不到唯一手写真相：{src}（派生链第一环的输入）"]
    mjs = HERE / "gen_file_assoc_manifest.mjs"
    if not mjs.is_file():
        return [f"找不到派生脚本：{mjs}"]
    node = shutil.which("node") or shutil.which("node.exe")
    if node is None:
        print("[gen-file-assoc-assets] [warn] 未找到 node："
              "跳过 manifest ↔ scratch-types.ts 核对（只核对三处资产）", file=sys.stderr)
        return []
    if not manifest.is_file():
        return [f"找不到 manifest：{manifest}（请运行 node scripts/gen_file_assoc_manifest.mjs）"]

    with tempfile.TemporaryDirectory(prefix="jflove-assoc-") as tmp:
        derived = Path(tmp) / MANIFEST_NAME
        proc = subprocess.run(
            [node, str(mjs), "--src", str(src), "--out", str(derived)],
            capture_output=True, text=True, encoding="utf-8", errors="replace",
        )
        if proc.returncode != 0 or not derived.is_file():
            tail = (proc.stderr or proc.stdout or "").strip()
            return [f"重跑派生失败（node exit={proc.returncode}）：{tail[-800:]}"]
        expected = derived.read_text(encoding="utf-8")

    disk = manifest.read_text(encoding="utf-8")
    if disk == expected:
        return []
    _print_diff(_rel(manifest), disk, expected)
    return [f"manifest 与 scratch-types.ts 的派生结果不一致：{_rel(manifest)}"
            "（手改生成物，或改完 TYPES 没重跑生成脚本）"]


def _rel(path: Path) -> str:
    """打印用的仓库根相对路径（跨平台统一正斜杠；不在仓库内时回退绝对路径）。"""
    try:
        return path.resolve().relative_to(REPO_ROOT).as_posix()
    except ValueError:
        return str(path)


