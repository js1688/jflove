#!/usr/bin/env python3
"""
打包资产派生脚本：`ui/public/file-assoc.manifest.json` → 三处打包资产（设计 v1.6.0 §5.1 / §6.7）

本脚本是派生链的**第二环**（第一环是 `scripts/gen_file_assoc_manifest.mjs`，
它把唯一手写真相 `ui/src/config/scratch-types.ts` 变成机器可读 manifest）：

    scratch-types.ts ──► file-assoc.manifest.json ──► ① packaging/linux/jflove.xml
        （唯一手写）        （生成物，随 dist 进包）      ② packaging/linux/jflove.desktop 的
                                                        `MimeType=` 行（标记注释包住，幂等重写）
                                                     ③ packaging/windows/file-assoc.iss
                                                        （.iss 的 [Registry] 段内片段）

## 为什么必须派生（AC-48a / §5.1 反例禁止）

`.iss` / `.desktop` / `.xml` 里**绝不允许**再手打扩展名清单：新增格式只改
`scratch-types.ts` 一处，随后重跑两个生成脚本即可全链路跟随。手打就会漂移，
而漂移的后果是"设置页显示的清单"与"系统注册的清单"各说各话。

## 用法

    python jflove-desktop/scripts/gen_file_assoc_assets.py                # 生成/覆盖三处资产
    python jflove-desktop/scripts/gen_file_assoc_assets.py --write        # 同上（显式写法）
    python jflove-desktop/scripts/gen_file_assoc_assets.py --check        # 只比对：0 一致 / 1 不一致
    python jflove-desktop/scripts/gen_file_assoc_assets.py --check --manifest <夹具.json>
    python jflove-desktop/scripts/gen_file_assoc_assets.py --root <目录>   # 夹具根（默认本脚本的上一级）

`--check` 做两件事，任一不通过即 exit 1 并打印 diff：

  ① **manifest ↔ 真相**：重跑 `gen_file_assoc_manifest.mjs`（Node 是派生链的**唯一**实现，
     不在 Python 里复刻一份格式），与磁盘上的 manifest 逐字节比对 ⇒ 手改 / 陈旧 manifest 立刻红；
  ② **资产 ↔ manifest**：按磁盘上的 manifest 重渲染三处资产，与磁盘逐行比对。
     （`--no-derive-check` 可只做 ②，供无 Node 的离线夹具场景使用；生产构建**不要**用它。）

## 平台边界（§6.7.2 / §6.7.3 / D18 / AC-43）

- Windows：只写 `HKCU\\Software\\Classes\\Applications\\JFLove.exe`（默认值 / `DefaultIcon` /
  `shell\\open\\command` / `SupportedTypes` 逐扩展名空值）。**绝不写** `Software\\Classes\\.<ext>`、
  绝不写 `FileExts\\.<ext>\\UserChoice`、绝不设 `ChangesAssociations`。卸载清理由
  `jflove.iss` 的 `[Code]` 按本文件导出的 `FILE_ASSOC_EXTS` 逐项删除（§6.7.2）。
- Linux：只装 `share/mime/packages/jflove.xml` + `.desktop` 的 `MimeType=`，由 RPM 的
  `%post`/`%postun` 跑 `update-mime-database`。**不调** `xdg-mime default`、不写
  `~/.config/mimeapps.list`（那会改默认程序）。
"""

